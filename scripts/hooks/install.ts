/**
 * Install the git pre-commit hook, which runs `deno task check`.
 *
 * Resolves shared .git/hooks/ directory (works with worktrees where
 * .git is a file, not a directory). Writes hook scripts directly
 * instead of depending on deno-task-hooks (which only supports a
 * limited subset of hook types).
 *
 * Earlier versions also installed post-checkout and post-merge hooks
 * that decrypted the owner's env files in this checkout. Those tasks
 * are gone, so a hook this installer left behind is removed: it would
 * fail after every checkout and merge. A hook somebody else wrote is
 * left alone.
 */

const COMMON_DIR = Deno.env.get("GIT_DIR") || resolveGitCommonDir()
const HOOKS_DIR = join(COMMON_DIR, "hooks")

// git exports GIT_DIR/GIT_COMMON_DIR/GIT_WORK_TREE/GIT_INDEX_FILE to a
// hook's own environment so a git command the hook runs targets the
// commit in progress. `deno task check` — this hook's own command —
// ends up spawning `git` itself too (a test suite that spawns `git` in
// a throwaway repo, or `cli/init.ts`'s own gitignore checks), and would
// inherit those same variables: such a spawn would then operate on the
// REAL repo/index/branch being committed instead of its own throwaway
// one — a real security review of this repo caught exactly that. Unset
// before running anything.
const UNSET_GIT_ENV = "unset GIT_DIR GIT_COMMON_DIR GIT_WORK_TREE GIT_INDEX_FILE"

/** First comment line of every hook this installer writes. */
const MARKER = "# Auto-generated by rostok hooks/install.ts"

const hooks: Record<string, string> = {
  "pre-commit": `#!/bin/sh
${MARKER}
set -eu
${UNSET_GIT_ENV}
deno task check
`,
}

/** Hooks earlier versions installed and this one no longer does. */
const RETIRED_HOOKS = ["post-checkout", "post-merge"]

function resolveGitCommonDir(): string {
  const cmd = new Deno.Command("git", {
    args: ["rev-parse", "--git-common-dir"],
    stdout: "piped",
    stderr: "piped",
  })
  const { code, stdout } = cmd.outputSync()
  if (code === 0) {
    return new TextDecoder().decode(stdout).trim()
  }
  // Fallback
  return join(Deno.cwd(), ".git")
}

function join(...parts: string[]): string {
  return parts.join("/")
}

async function main() {
  console.log(`Installing hooks in: ${HOOKS_DIR}`)

  try {
    await Deno.mkdir(HOOKS_DIR, { recursive: true })
  } catch { /* exists */ }

  let installed = 0
  for (const [name, script] of Object.entries(hooks)) {
    const path = join(HOOKS_DIR, name)
    try {
      // Check if already installed with same content
      const existing = await Deno.readTextFile(path)
      if (existing.trim() === script.trim()) {
        console.log(`  ${name}: already installed`)
        continue
      }
    } catch { /* not exists — install */ }

    await Deno.writeTextFile(path, script)
    if (Deno.build.os !== "windows") {
      await Deno.chmod(path, 0o755)
    }
    console.log(`  ${name}: installed`)
    installed++
  }

  let removed = 0
  for (const name of RETIRED_HOOKS) {
    const path = join(HOOKS_DIR, name)
    let existing: string
    try {
      existing = await Deno.readTextFile(path)
    } catch {
      continue // not installed
    }
    if (!existing.includes(MARKER)) {
      console.log(`  ${name}: not written by this installer, left alone`)
      continue
    }
    await Deno.remove(path)
    console.log(`  ${name}: removed (no longer used)`)
    removed++
  }

  console.log(`\nDone. ${installed} hook(s) installed, ${removed} removed.`)
}

if (import.meta.main) await main()
