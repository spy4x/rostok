import { assert, assertEquals, assertStringIncludes } from "@std/assert"
import { fromFileUrl, join } from "@std/path"

const INSTALLER = fromFileUrl(new URL("./install.ts", import.meta.url))

/** Runs the installer against a throwaway git directory. */
async function install(gitDir: string): Promise<void> {
  const { code, stderr } = await new Deno.Command(Deno.execPath(), {
    args: ["run", "-R", "-W", "--allow-run=git", "--allow-env=GIT_DIR", INSTALLER],
    env: { GIT_DIR: gitDir },
    stdout: "null",
    stderr: "piped",
  }).output()
  assertEquals(code, 0, new TextDecoder().decode(stderr))
}

async function exists(path: string): Promise<boolean> {
  try {
    await Deno.stat(path)
    return true
  } catch {
    return false
  }
}

Deno.test("installs a pre-commit hook that runs only deno task check", async () => {
  const gitDir = await Deno.makeTempDir()
  try {
    await install(gitDir)
    const hook = await Deno.readTextFile(join(gitDir, "hooks", "pre-commit"))
    const commands = hook.split("\n").filter((line) => line.startsWith("deno "))
    assertEquals(commands, ["deno task check"])
    assert(!await exists(join(gitDir, "hooks", "post-checkout")))
    assert(!await exists(join(gitDir, "hooks", "post-merge")))
  } finally {
    await Deno.remove(gitDir, { recursive: true })
  }
})

Deno.test("replaces the old pre-commit hook that also encrypted env files", async () => {
  const gitDir = await Deno.makeTempDir()
  try {
    await Deno.mkdir(join(gitDir, "hooks"))
    await Deno.writeTextFile(
      join(gitDir, "hooks", "pre-commit"),
      "#!/bin/sh\n# Auto-generated by rostok hooks/install.ts\nset -eu\n" +
        "deno task check && deno task env:encrypt\n",
    )
    await install(gitDir)
    const hook = await Deno.readTextFile(join(gitDir, "hooks", "pre-commit"))
    assert(!hook.includes("env:encrypt"), hook)
    assertStringIncludes(hook, "deno task check\n")
  } finally {
    await Deno.remove(gitDir, { recursive: true })
  }
})

Deno.test("removes the env-decrypt hooks an earlier version installed", async () => {
  const gitDir = await Deno.makeTempDir()
  try {
    await Deno.mkdir(join(gitDir, "hooks"))
    const old = "#!/bin/sh\n# Auto-generated by rostok hooks/install.ts\nset -eu\n" +
      "deno task env:decrypt\n"
    await Deno.writeTextFile(join(gitDir, "hooks", "post-checkout"), old)
    await Deno.writeTextFile(join(gitDir, "hooks", "post-merge"), old)
    await install(gitDir)
    assert(!await exists(join(gitDir, "hooks", "post-checkout")))
    assert(!await exists(join(gitDir, "hooks", "post-merge")))
  } finally {
    await Deno.remove(gitDir, { recursive: true })
  }
})

Deno.test("leaves a post-checkout hook somebody else wrote", async () => {
  const gitDir = await Deno.makeTempDir()
  try {
    await Deno.mkdir(join(gitDir, "hooks"))
    const own = "#!/bin/sh\necho mine\n"
    await Deno.writeTextFile(join(gitDir, "hooks", "post-checkout"), own)
    await install(gitDir)
    assertEquals(await Deno.readTextFile(join(gitDir, "hooks", "post-checkout")), own)
  } finally {
    await Deno.remove(gitDir, { recursive: true })
  }
})
